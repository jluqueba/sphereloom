"""The public capability matrix, rendered from the registry.

`docs/CAPABILITIES.md` is generated from this module, so the public page cannot claim more,
or less, than the code (AC-2.1.4, ADR-0016). Only the table between two markers is
generated; the prose around it is written by hand.

The labels and notes below are presentation only. The state of each capability, and the
reason for any capability that is not available, come from the registry.
"""

from __future__ import annotations

from sphereloom.capabilities.registry import CapabilityRegistry
from sphereloom.domain.capabilities import Capability, CapabilityState

BEGIN_MARKER = "<!-- capability-matrix:begin (generated by scripts/render_capability_matrix.py) -->"
END_MARKER = "<!-- capability-matrix:end -->"

#: How each state is written on the public page (ADR-0016).
STATE_LABELS: dict[CapabilityState, str] = {
    CapabilityState.AVAILABLE: "Available",
    CapabilityState.NOT_YET_AVAILABLE: "Not yet available",
    CapabilityState.UNSUPPORTED_BY_VENDOR: "Not supported by the vendor API",
}

#: What each capability does, in a user's words.
LABELS: dict[Capability, str] = {
    Capability.CAMERA_CONNECT: "Connect to the camera",
    Capability.CAMERA_STATUS: "Read battery, storage and capture state",
    Capability.OPTIONS_READ: "Read capture settings",
    Capability.OPTIONS_WRITE: "Change capture settings",
    Capability.PHOTO_CAPTURE: "Take a 360° photo",
    Capability.VIDEO_RECORD: "Record video",
    Capability.FILES_LIST: "Browse the gallery",
    Capability.FILES_DOWNLOAD: "Download media to the workspace",
    Capability.FILES_DELETE: "Delete media from the camera",
    Capability.EXPOSURE_CONTROL: "Exposure and white balance control",
    Capability.PREVIEW_LIVE: "Live preview or streaming",
    Capability.STORAGE_FORMAT: "Format the storage card",
    Capability.MEDIA_STITCH_VIDEO: "Stitch video into a 360° video",
    Capability.MEDIA_EXPORT: "Export processed media",
}

#: Facts worth knowing whatever the state. Where none is given, an unavailable capability
#: shows the registry's reason.
_NEEDS_MEDIA_SDK = "Needs the Insta360 Media SDK, which you obtain yourself, and an NVIDIA GPU"

NOTES: dict[Capability, str] = {
    Capability.CAMERA_CONNECT: "Requires joining the camera's Wi-Fi access point",
    Capability.CAMERA_STATUS: "Reports what the camera supplies; missing values are empty",
    Capability.OPTIONS_READ: "Limited to what the camera's Wi-Fi API exposes",
    Capability.OPTIONS_WRITE: "Limited to what the camera's Wi-Fi API exposes",
    Capability.PHOTO_CAPTURE: "Photos are stitched in the camera",
    Capability.VIDEO_RECORD: "Video is recorded **unstitched**",
    Capability.FILES_LIST: "Newest first, a page at a time",
    Capability.FILES_DOWNLOAD: "Runs as a cancellable background job",
    Capability.FILES_DELETE: "Disabled by default; needs a confirmation token",
    Capability.MEDIA_STITCH_VIDEO: _NEEDS_MEDIA_SDK,
    Capability.MEDIA_EXPORT: _NEEDS_MEDIA_SDK,
}


def render_table(registry: CapabilityRegistry) -> str:
    """Return the Markdown table of every capability, in declaration order."""
    rows = [
        "| Capability | Identifier | Status | Notes |",
        "| --- | --- | --- | --- |",
    ]
    for status in registry.resolve_all():
        note = NOTES.get(status.capability) or (status.reason or "")
        cells = [
            LABELS[status.capability],
            f"`{status.capability.value}`",
            STATE_LABELS[status.status],
            note.removesuffix("."),
        ]
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def render_section(registry: CapabilityRegistry) -> str:
    """Return the generated section, markers included."""
    return f"{BEGIN_MARKER}\n\n{render_table(registry)}\n\n{END_MARKER}"


def replace_section(document: str, section: str) -> str:
    """Return `document` with its generated section replaced by `section`.

    Raises:
        ValueError: if the markers are missing, repeated or out of order.
    """
    begin = document.find(BEGIN_MARKER)
    end = document.find(END_MARKER)
    if (
        begin < 0
        or end < begin
        or document.count(BEGIN_MARKER) != 1
        or document.count(END_MARKER) != 1
    ):
        message = "The document must contain each capability matrix marker once, in order."
        raise ValueError(message)
    return document[:begin] + section + document[end + len(END_MARKER) :]
